// 教学假设：卯初、酉初分界。每段六个时辰，显示该时辰起止的累计周数。
export function weiAt(index) {
  const step = index % 6;
  const start = 25 * step / 6;
  const end = 25 * (step + 1) / 6;
  const fmt = n => Number(n.toFixed(1));
  return {
    phase: index < 6 ? "day" : "night",
    label: index < 6 ? "昼行阳分" : "夜行阴分",
    start, end, range: `约 ${fmt(start)}–${fmt(end)} / 共 25 度`,
  };
}
